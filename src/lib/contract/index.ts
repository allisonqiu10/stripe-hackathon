import { z } from 'zod';
export const IdSchema = z.string().min(1);
export const CentsSchema = z.number().int().min(0).max(2147483647);
export const RuleTypeSchema = z.enum(['ROUND_UP', 'PERCENTAGE']);
export const CauseStatusSchema = z.enum(['DRAFT', 'ACTIVE', 'CLOSED']);
export const CreateCauseRequestSchema = z.object({title:z.string().trim().min(1),description:z.string().trim().min(1),city:z.string().trim().min(1),goalCents:CentsSchema.positive(),ownerName:z.string().trim().min(1)});
export const CauseSchema = CreateCauseRequestSchema.extend({id:IdSchema,slug:IdSchema,stripeAccountId:IdSchema.nullable(),onboardingComplete:z.boolean(),status:CauseStatusSchema});
export const CreateMerchantRequestSchema = z.object({name:z.string().trim().min(1),email:z.email()});
export const UpdateMerchantRequestSchema = z.object({ruleType:RuleTypeSchema.optional(),percentageBps:z.number().int().min(0).max(10000).optional(),activeCauseId:IdSchema.nullable().optional()});
export const MerchantSchema = CreateMerchantRequestSchema.extend({id:IdSchema,stripeAccountId:IdSchema.nullable(),onboardingComplete:z.boolean(),ruleType:RuleTypeSchema,percentageBps:z.number().int().min(0).max(10000),activeCauseId:IdSchema.nullable()});
export const OrderSchema = z.object({id:IdSchema,merchantId:IdSchema,causeId:IdSchema.nullable(),paymentIntentId:IdSchema,itemAmountCents:CentsSchema,donationCents:CentsSchema,totalCents:CentsSchema,ruleType:RuleTypeSchema,status:z.enum(['PENDING','PAID','REFUNDED','FAILED'])});
export const DonationSchema = z.object({id:IdSchema,orderId:IdSchema,causeId:IdSchema,merchantId:IdSchema,paymentIntentId:IdSchema,kind:RuleTypeSchema,amountCents:CentsSchema,platformFeeCents:CentsSchema,status:z.enum(['PENDING','TRANSFERRED','REFUNDED','FAILED']),merchantTransferId:IdSchema.nullable(),causeTransferId:IdSchema.nullable(),createdAt:z.iso.datetime()});
export const ListCausesRequestSchema = z.object({city:z.string().optional(),status:CauseStatusSchema.optional()});
export const CauseProgressResponseSchema = z.object({raisedCents:z.number().int().nonnegative(),goalCents:CentsSchema,donorCount:z.number().int().nonnegative(),recent:z.array(z.object({amountCents:CentsSchema,createdAt:z.iso.datetime()}))});
export const MerchantImpactResponseSchema = z.object({totalDonatedCents:z.number().int().nonnegative(),orderCount:z.number().int().nonnegative(),donationCount:z.number().int().nonnegative(),byCause:z.array(z.object({causeId:IdSchema,title:z.string(),amountCents:z.number().int().nonnegative()}))});
export const CheckoutQuoteRequestSchema = z.object({merchantId:IdSchema,itemAmountCents:CentsSchema.positive(),roundUp:z.boolean()});
export const QuoteSchema = CheckoutQuoteRequestSchema.extend({causeId:IdSchema,donationCents:CentsSchema,totalCents:CentsSchema,ruleType:RuleTypeSchema});
export const CheckoutIntentRequestSchema = CheckoutQuoteRequestSchema;
export const CheckoutIntentResponseSchema = z.object({clientSecret:z.string().min(1),paymentIntentId:IdSchema,quote:QuoteSchema});
export const MerchantOnboardRequestSchema = z.object({merchantId:IdSchema});
export const CauseOnboardRequestSchema = z.object({causeId:IdSchema});
export const OnboardResponseSchema = z.object({url:z.url()});
export const ConnectStatusRequestSchema = z.object({kind:z.enum(['merchant','cause']),id:IdSchema});
export const ConnectStatusResponseSchema = z.object({onboardingComplete:z.boolean(),requirementsDue:z.array(z.string())});
export const ErrorResponseSchema = z.object({error:z.string()});
export const CreateCauseResponseSchema = CauseSchema;
export const GetCauseResponseSchema = CauseSchema;
export const ListCausesResponseSchema = z.array(CauseSchema);
export const CreateMerchantResponseSchema = MerchantSchema;
export const GetMerchantResponseSchema = MerchantSchema;
export const UpdateMerchantResponseSchema = MerchantSchema;
export const CheckoutQuoteResponseSchema = QuoteSchema;

export type Id = z.infer<typeof IdSchema>;
export type Cents = z.infer<typeof CentsSchema>;
export type RuleType = z.infer<typeof RuleTypeSchema>;
export type CauseStatus = z.infer<typeof CauseStatusSchema>;
export type CreateCauseRequest = z.infer<typeof CreateCauseRequestSchema>;
export type Cause = z.infer<typeof CauseSchema>;
export type CreateMerchantRequest = z.infer<typeof CreateMerchantRequestSchema>;
export type UpdateMerchantRequest = z.infer<typeof UpdateMerchantRequestSchema>;
export type Merchant = z.infer<typeof MerchantSchema>;
export type Order = z.infer<typeof OrderSchema>;
export type Donation = z.infer<typeof DonationSchema>;
export type ListCausesRequest = z.infer<typeof ListCausesRequestSchema>;
export type CauseProgressResponse = z.infer<typeof CauseProgressResponseSchema>;
export type MerchantImpactResponse = z.infer<typeof MerchantImpactResponseSchema>;
export type CheckoutQuoteRequest = z.infer<typeof CheckoutQuoteRequestSchema>;
export type Quote = z.infer<typeof QuoteSchema>;
export type CheckoutIntentRequest = z.infer<typeof CheckoutIntentRequestSchema>;
export type CheckoutIntentResponse = z.infer<typeof CheckoutIntentResponseSchema>;
export type MerchantOnboardRequest = z.infer<typeof MerchantOnboardRequestSchema>;
export type CauseOnboardRequest = z.infer<typeof CauseOnboardRequestSchema>;
export type OnboardResponse = z.infer<typeof OnboardResponseSchema>;
export type ConnectStatusRequest = z.infer<typeof ConnectStatusRequestSchema>;
export type ConnectStatusResponse = z.infer<typeof ConnectStatusResponseSchema>;
export type ErrorResponse = z.infer<typeof ErrorResponseSchema>;
export type CreateCauseResponse = z.infer<typeof CreateCauseResponseSchema>;
export type GetCauseResponse = z.infer<typeof GetCauseResponseSchema>;
export type ListCausesResponse = z.infer<typeof ListCausesResponseSchema>;
export type CreateMerchantResponse = z.infer<typeof CreateMerchantResponseSchema>;
export type GetMerchantResponse = z.infer<typeof GetMerchantResponseSchema>;
export type UpdateMerchantResponse = z.infer<typeof UpdateMerchantResponseSchema>;
export type CheckoutQuoteResponse = z.infer<typeof CheckoutQuoteResponseSchema>;
